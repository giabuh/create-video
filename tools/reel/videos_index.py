"""Per-video motion components: studio/src/videos/<slug>/index.ts -> generated studio/src/videos/index.ts."""
import re
from pathlib import Path

HEADER = "// generated by tools/reel/videos_index.py — do not edit\n"
ENTRY = re.compile(r"^\s+(\w+): defineMotion\(", re.M)


def video_motion_keys(root: Path) -> dict[str, list[str]]:
    """{slug: [Name, ...]} read from each studio/src/videos/<slug>/index.ts, sorted by slug."""
    out = {}
    for idx in sorted((Path(root) / "studio/src/videos").glob("*/index.ts")):
        out[idx.parent.name] = ENTRY.findall(idx.read_text())
    return out


def write_videos_index(root: Path) -> bool:
    """Regenerate studio/src/videos/index.ts; True if the file changed."""
    vids = Path(root) / "studio/src/videos"
    vids.mkdir(parents=True, exist_ok=True)
    keys = video_motion_keys(root)
    lines = [HEADER, "import type {MotionDef} from '../motion/schema';\n"]
    lines += [f"import {{MOTION as v{i}}} from './{slug}';\n" for i, slug in enumerate(keys)]
    lines.append("\nexport const VIDEO_MOTION: Record<string, MotionDef> = {\n")
    lines += [f"  '{slug}/{n}': v{i}.{n},\n" for i, (slug, names) in enumerate(keys.items()) for n in names]
    lines.append("};\n")
    text = "".join(lines)
    f = vids / "index.ts"
    if f.exists() and f.read_text() == text:
        return False
    f.write_text(text)
    return True
